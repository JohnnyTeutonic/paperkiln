#!/usr/bin/env python3
"""The PTQ cost on the laptop's CPU (LOCAL_LLM_WORK R3; experiments/lowbit_2026-10-28). The Colab version is
lowbit_vm.py ptq/carry5; this one runs the same steps on ptq_home.sh's exports at 2 cores, with the samples
stated in each record (the CPU cannot carry the full sets for 20 model files).

    python3 ptq_eval_home.py panels TAG VARIANT [--windows N]
    python3 ptq_eval_home.py bench TAG VARIANT [--every N]
    python3 ptq_eval_home.py carry5 TAG VARIANT [--every N]

TAG's exports are ~/r3_ptq/TAG/<name>[_VARIANT].gguf. Each variant is dequantised (dequant.py) to untied F32
weights in ~/r3_ptq/TAG/VARIANT/, the model ember computes from the quantised file. panels: tiny_chat_run's
zero-rate pass (1 step at lr 0, then the mean loss over the held-out windows) on E1's two panel files, CPU
mtstudio, N windows (default 128 of the post jobs' 512; the same windows for every variant, so the
differences are paired). bench: bench_eval.py hfgguf on the quantised file itself (transformers dequantises
with gguf-py), torch on the CPU, every N-th item. carry5: carry5_eval.py with the self history generated by
ember (757e36b, CPU) on the quantised GGUF and forced choice by CPU `mtstudio score` on the dequantised
weights; every N-th item. Records: ~/r3_ptq/results/TAG_VARIANT_{panels,bench,carry5}.json.
"""
import argparse
import hashlib
import json
import os
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(REPO, "tools", "colab_chat"))
sys.path.insert(0, os.path.join(REPO, "tools"))
W = os.path.expanduser(os.environ.get("R3_WORK", "~/r3_ptq"))
MT = os.path.expanduser(os.environ.get("MT", "~/r3_build/mtstudio"))
EMBER = os.path.expanduser(os.environ.get("EMBER_BIN", "~/r3_ember/tinyllama_server_757e36b"))
VOCAB = "/mnt/c/ml_artifacts/capacity/vocab/vocab_llama3_bpe.gguf"
PANELS = {"fineweb": "/mnt/c/ml_artifacts/lowbit/ternary/panels_home/panel_fineweb.ids",
          "dialogue": os.path.expanduser("~/r3_data/out/panel_dialogue.ids")}
PANEL_SHA = {"fineweb": "c1aa6d42aafe80d8607b2d1f19235eb1539ccd94997567c506ae68f330c06e6b",
             "dialogue": "7881aa1c196e30b692a18ba2704a49333a78d8ce059dedb98e794baa0838258a"}
ITEMS = os.path.expanduser("~/r3_bench/bench_v1.jsonl")
ITEMS_SHA = "978548d1c64f9a361c2e3d210e889955061bd7f71a496ab6a7734caf3969033c"
ENV = {**os.environ, "MICROTORCH_DEVICE": "cpu", "CUDA_VISIBLE_DEVICES": "", "OMP_NUM_THREADS": "2",
       "JOBS_MTSTUDIO": MT}
os.environ.update(ENV)


def sha256(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for c in iter(lambda: f.read(1 << 20), b""):
            h.update(c)
    return h.hexdigest()


def jsave(p, o):
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p + ".tmp", "w") as f:
        json.dump(o, f, indent=1)
    os.replace(p + ".tmp", p)


def variant(tag, v):
    d = os.path.join(W, tag)
    s = json.load(open(os.path.join(d, "spec.json")))
    g = os.path.join(d, s["name"] + ("" if v == "f32" else "_" + v) + ".gguf")
    vd = os.path.join(d, v)
    os.makedirs(vd, exist_ok=True)
    name = f"{tag}_{v}"
    w = os.path.join(vd, name + ".safetensors")
    if not os.path.exists(w):
        p = subprocess.run([sys.executable, os.path.join(HERE, "dequant.py"), g, w], capture_output=True, text=True)
        if p.returncode:
            raise SystemExit(p.stderr[-800:])
        open(os.path.join(vd, "dequant.json"), "w").write(p.stdout)
    link = os.path.join(vd, name + ".gguf")
    if not os.path.lexists(link):
        os.symlink(g, link)
    arch = json.loads(json.dumps(s["arch"]))
    arch["custom"]["tie_embeddings"] = False
    spec = {"name": name, "arch": arch, "data": {**s["data"], "vocab": VOCAB},
            "train": {"steps": 1, "lr": 0.0, "batch": 1, "seed": 1}, "export": {"formats": []}, "out_dir": vd}
    jsave(os.path.join(vd, "spec.json"), spec)
    return vd, spec, w, g


def cmd_panels(a):
    import tiny_chat_run as tc
    tc.PANEL_WINDOWS = a.windows
    out = os.path.join(W, "results", f"{a.tag}_{a.variant}_panels.json")
    vd, spec, w, g = variant(a.tag, a.variant)
    for k, p in PANELS.items():
        if sha256(p) != PANEL_SHA[k]:
            raise SystemExit(f"{p} is not E1's {k} panel")
    t0 = time.time()
    work = os.path.join(vd, f"panels_w{a.windows}")
    res = tc.zero_rate_panels({"arch": spec["arch"], "data": spec["data"]}, w, work,
                              [f"{k}={p}" for k, p in PANELS.items()])
    jsave(out, {"tag": a.tag, "variant": a.variant, "windows": a.windows, "panels": res,
                "gguf_sha256": sha256(g), "weights_sha256": sha256(w), "seconds": round(time.time() - t0, 1)})
    print(json.dumps(res))


def items():
    if not os.path.exists(ITEMS):
        os.makedirs(os.path.dirname(ITEMS) + "/raw", exist_ok=True)
        subprocess.run([sys.executable, "-I", "tools/bench_build.py", "fetch", "--raw", os.path.dirname(ITEMS) + "/raw"],
                       cwd=REPO, check=True)
        subprocess.run([sys.executable, "-I", "tools/bench_build.py", "build", "--raw", os.path.dirname(ITEMS) + "/raw",
                        "--out", ITEMS], cwd=REPO, check=True)
    if sha256(ITEMS) != ITEMS_SHA:
        raise SystemExit(f"{ITEMS} is not the pinned item file")


def cmd_bench(a):
    items()
    vd, spec, w, g = variant(a.tag, a.variant)
    t0 = time.time()
    o = os.path.join(W, "bench_every%d" % a.every)
    p = subprocess.run([sys.executable, "tools/bench_eval.py", "run", "--items", ITEMS, "--out", o, "--scorer", "hfgguf",
                        "--device", "cpu", "--model", f"{a.tag}_{a.variant}={os.path.join(vd, 'spec.json')}",
                        "--blimp-per", "100", "--every", str(a.every)], cwd=REPO)
    sm = os.path.join(o, f"{a.tag}_{a.variant}", "summary.json")
    if p.returncode or not os.path.exists(sm):
        raise SystemExit("bench_eval failed")
    jsave(os.path.join(W, "results", f"{a.tag}_{a.variant}_bench.json"),
          {"tag": a.tag, "variant": a.variant, "every": a.every, "summary": json.load(open(sm)),
           "gguf_sha256": sha256(g), "seconds": round(time.time() - t0, 1)})


def cmd_carry5(a):
    import tiny_chat_run as tc
    vd, spec, w, g = variant(a.tag, a.variant)
    c5 = os.path.join(vd, f"carry5_every{a.every}")
    t0 = time.time()
    argv = tc.carry5_argv(os.path.join(vd, "spec.json"), "corpus/eval/carry5_v1.jsonl", c5, "ember",
                          8140 + (abs(hash(a.tag + a.variant)) % 50), ember={"bin": EMBER, "gpu_layers": "0"},
                          extra=["--every", str(a.every)] if a.every > 1 else [])
    argv[argv.index("--mtstudio") + 1] = MT
    p = subprocess.run(argv, cwd=REPO, capture_output=True, text=True, env=ENV)
    open(os.path.join(vd, f"carry5_every{a.every}.log"), "w").write(p.stdout[-20000:] + p.stderr[-20000:])
    if p.returncode or not os.path.exists(os.path.join(c5, "summary.json")):
        raise SystemExit(f"carry5_eval failed: {p.stderr[-800:]}")
    c = tc.carry5_read(c5)
    jsave(os.path.join(W, "results", f"{a.tag}_{a.variant}_carry5.json"),
          {"tag": a.tag, "variant": a.variant, "every": a.every, "primary": tc.primary(c),
           "primary_all_items": tc.primary_all_items(c), "gate": c["summary"].get("gate"),
           "gguf_sha256": sha256(g), "seconds": round(time.time() - t0, 1)})
    print(tc.primary(c))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["panels", "bench", "carry5"])
    ap.add_argument("tag")
    ap.add_argument("variant")
    ap.add_argument("--windows", type=int, default=128)
    ap.add_argument("--every", type=int, default=1)
    a = ap.parse_args()
    os.chdir(REPO)
    {"panels": cmd_panels, "bench": cmd_bench, "carry5": cmd_carry5}[a.cmd](a)
