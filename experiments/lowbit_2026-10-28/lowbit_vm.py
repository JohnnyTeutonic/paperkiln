#!/usr/bin/env python3
"""VM side of LOCAL_LLM_WORK R3's measurements (experiments/lowbit_2026-10-28; runner_multi "cmd" jobs).

    python3 lowbit_vm.py gate OUT                       test_bitlinear on the device + the data job's hashes
    python3 lowbit_vm.py ptq OUT TAG                    post-training quantisation of one model: exports,
                                                        dequantised weights, panels, benchmarks
    python3 lowbit_vm.py carry5 OUT TAG VARIANT         Carry-5 of one quantised pick (after its ptq job)
    python3 lowbit_vm.py bench_mt OUT SPEC              the benchmarks through `mtstudio score` (a BitLinear
                                                        model: no GGUF form, so no hfgguf)

ptq: TAG's F32 weights are the upload /content/chat/upload/TAG.safetensors (tied, paperkiln names) and its
arch is experiments/benchmarks_2026-10-26/specs/TAG.spec.json. `mtstudio export` writes the F32, Q8_0
(gguf_q8_0_all: every matrix, llama-quantize's Q8_0), Q4_K_M, Q4_K_S and Q4_0 GGUFs (paperkiln's quantiser is
byte-identical to llama.cpp b6000's llama-quantize, LOCAL_LLM_STACK.md section 10, 25 Oct 2026); each is
dequantised (dequant.py) to untied F32 weights, the model ember computes. Per variant: the two text panels
(tiny_chat_run's zero-rate pass, nats/token on 512 held-out windows), and the seven benchmarks through
transformers' GGUF loader on the quantised file itself (bench_eval hfgguf; transformers dequantises with
gguf-py, so the same values). Everything lands in OUT/TAG/<variant>/ and OUT/summary_TAG.json; the
dequantised weights stay in /content/eval_r3/ for the carry5 jobs and are never brought home.

carry5: tiny_chat_run's Carry-5 stage on the dequantised weights: forced choice by `mtstudio score`, the self
history generated by ember on the quantised GGUF itself after the 40-item spot-check against `mtstudio chat`
(else mtstudio throughout, flagged), as E1's post jobs did.
"""
