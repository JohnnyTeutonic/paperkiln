def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def jsave(path, obj):
    with open(path + ".tmp", "w") as f:
        json.dump(obj, f, indent=1)
    os.replace(path + ".tmp", path)


def jload(path):
    with open(path) as f:
        return json.load(f)


def gguf_deps(out):
    """gguf-py from llama.cpp b6000 and transformers 4.46.3 (bench_vm.sh's pins), under its pip lock."""
    p = subprocess.run(["bash", "-c", f"""
set -e
exec 9> /content/bench_pip.lock
flock 9
python3 -c "import huggingface_hub" 2>/dev/null || python3 -m pip -q install --root-user-action=ignore --force-reinstall "huggingface_hub==0.26.2"
python3 -c "import transformers" 2>/dev/null || python3 -m pip -q install --root-user-action=ignore "transformers==4.46.3"
[ -d /content/llamacpp_b6000 ] || git clone -q --depth 1 --branch b6000 https://github.com/ggml-org/llama.cpp /content/llamacpp_b6000
python3 -c "import gguf, accelerate" 2>/dev/null || python3 -m pip -q install --root-user-action=ignore /content/llamacpp_b6000/gguf-py "accelerate==1.1.1"
python3 -c "import torch, transformers, gguf; print(torch.__version__, transformers.__version__)"
"""], capture_output=True, text=True)
    open(os.path.join(out, "deps.log"), "a").write(p.stdout + p.stderr)
    if p.returncode != 0:
        raise SystemExit(f"dependencies failed: {p.stderr[-800:]}")


def items():
    """The benchmark item file, built once per VM (bench_vm.sh items)."""
    import fcntl
    os.makedirs("/content/bench/raw", exist_ok=True)
    lock = open("/content/bench/items.lock", "w")
    fcntl.flock(lock, fcntl.LOCK_EX)  # parallel ptq jobs build the file once
    if os.path.exists(ITEMS):
        return
    with open("/content/bench/fetch.log", "a") as log:
        subprocess.run([sys.executable, "-I", "tools/bench_build.py", "fetch", "--raw", "/content/bench/raw"],
                       cwd=REPO, stdout=log, stderr=subprocess.STDOUT, check=True)
        with open("/content/bench/items_build.json", "w") as o:
            subprocess.run([sys.executable, "-I", "tools/bench_build.py", "build", "--raw", "/content/bench/raw",
                            "--out", ITEMS + ".tmp"], cwd=REPO, stdout=o, stderr=log, check=True)
    os.replace(ITEMS + ".tmp", ITEMS)


# ---------------------------------------------------------------- gate
def cmd_gate(out):
    res = {"time": time.strftime("%Y-%m-%d %H:%M:%S")}
    led = jload("/content/chat/data/data.ledger.json")
    got = {k: led["steps"][k]["sha256"] for k in E1_DATA}
    res["data"] = {"got": got, "e1": E1_DATA, "same": got == E1_DATA}
    b = subprocess.run(["make", "-j4", "test_bitlinear"], cwd=BUILD, capture_output=True, text=True)
    res["build_rc"] = b.returncode
    t = subprocess.run([f"{BUILD}/test_bitlinear"], cwd=BUILD, capture_output=True, text=True,
                       env={**os.environ, **DEV_ENV})
    open(os.path.join(out, "test_bitlinear.txt"), "w").write(b.stdout[-3000:] + b.stderr[-3000:] + t.stdout + t.stderr)
    res["test_rc"] = t.returncode
    res["cuda_leg_ran"] = "device ternary_fwd == CPU" in t.stdout
    res["ok"] = res["data"]["same"] and b.returncode == 0 and t.returncode == 0 and res["cuda_leg_ran"]
    jsave(os.path.join(out, "gate.json"), res)
    print(json.dumps(res))
    return 0 if res["ok"] else 1


# ---------------------------------------------------------------- ptq
def stage(tag):
    """F32 weights and the five GGUF variants in EVAL/TAG (exported once)."""
    d = os.path.join(EVAL, tag)
    os.makedirs(d, exist_ok=True)
    s = jload(f"{REPO}/experiments/benchmarks_2026-10-26/specs/{tag}.spec.json")
    s["data"]["vocab"] = f"{U}/{os.path.basename(s['data']['vocab'])}"
    s["out_dir"] = d
    jsave(os.path.join(d, "spec.json"), s)
    st = f"{U}/{tag}.safetensors"
    link = os.path.join(d, s["name"] + ".safetensors")
    if not os.path.lexists(link):
        os.symlink(st, link)
    names = {"f32": s["name"] + ".gguf", **{v: f"{s['name']}_{v}.gguf" for v in VARIANTS[1:]}}
    import fcntl
    lock = open(os.path.join(d, "export.lock"), "w")
    fcntl.flock(lock, fcntl.LOCK_EX)  # carry5 jobs on a replacement VM export once
    if not all(os.path.exists(os.path.join(d, n)) for n in names.values()):
        with open(os.path.join(d, "export.log"), "a") as log:
            p = subprocess.run([MT, "export", os.path.join(d, "spec.json"), "--from", st, "--formats",
                                "gguf," + ",".join("gguf_" + v for v in VARIANTS[1:])], stdout=log,
                               stderr=subprocess.STDOUT, env={**os.environ, **DEV_ENV})
        if p.returncode != 0:
            raise SystemExit(f"{tag}: mtstudio export failed (rc {p.returncode}; {d}/export.log)")
    return d, s, {v: os.path.join(d, n) for v, n in names.items()}


def variant_dir(tag, v, s, gguf):
    """EVAL/TAG/V: the dequantised untied weights and a spec naming them; the quantised GGUF linked as
    <name>.gguf beside them (what ember and hfgguf read)."""
    vd = os.path.join(EVAL, tag, v)
    os.makedirs(vd, exist_ok=True)
    name = f"{tag}_{v}"
    w = os.path.join(vd, name + ".safetensors")
    if not os.path.exists(w):
        p = subprocess.run([sys.executable, os.path.join(HERE, "dequant.py"), gguf, w], capture_output=True, text=True)
        if p.returncode != 0:
            raise SystemExit(f"dequant {gguf}: {p.stderr[-800:]}")
        open(os.path.join(vd, "dequant.json"), "w").write(p.stdout)
    g = os.path.join(vd, name + ".gguf")
    if not os.path.lexists(g):
        os.symlink(gguf, g)
    arch = json.loads(json.dumps(s["arch"]))
    arch["custom"]["tie_embeddings"] = False
    spec = {"name": name, "arch": arch, "data": s["data"], "train": {"steps": 1, "lr": 0.0, "batch": 1, "seed": 1},
            "export": {"formats": []}, "out_dir": vd}
    jsave(os.path.join(vd, "spec.json"), spec)
    return vd, spec, w


def cmd_ptq(out, tag):
    import tiny_chat_run as tc
    # E1's panel files (uploaded; the ternary campaign's data job brought them home), checked by hash.
    os.makedirs("/content/chat/data", exist_ok=True)
    for name in ("panel_fineweb", "panel_dialogue"):
        dst, src = f"/content/chat/data/{name}.ids", f"{U}/{name}.ids"
        if not os.path.exists(dst):
            shutil.copyfile(src, dst + ".tmp")
            os.replace(dst + ".tmp", dst)
        if sha256(dst) != E1_DATA[name]:
            raise SystemExit(f"{dst} is not E1's {name} (sha256 {sha256(dst)})")
    gguf_deps(out)
    items()
    d, s, ggufs = stage(tag)
    summ_path = os.path.join(out, f"summary_{tag}.json")
    summ = jload(summ_path) if os.path.exists(summ_path) else {"tag": tag, "variants": {}}
    summ["f32_safetensors_sha256"] = sha256(f"{U}/{tag}.safetensors")
    for v in VARIANTS:
        rec = summ["variants"].setdefault(v, {})
        rec["gguf"] = os.path.basename(ggufs[v])
        rec["gguf_bytes"] = os.path.getsize(ggufs[v])
        rec["gguf_sha256"] = rec.get("gguf_sha256") or sha256(ggufs[v])
        vd, spec, w = variant_dir(tag, v, s, ggufs[v])
        rec["dequant"] = json.loads(open(os.path.join(vd, "dequant.json")).read() or "{}")
        o = os.path.join(out, tag, v)
        os.makedirs(o, exist_ok=True)
        if "panels" not in rec:
            shape = {"arch": spec["arch"], "data": spec["data"]}
            os.environ.update(DEV_ENV)
            rec["panels"] = tc.zero_rate_panels(shape, w, o, PANELS)
            jsave(summ_path, summ)
        if "bench" not in rec:
            with open(os.path.join(o, "bench.log"), "a") as log:
                p = subprocess.run([sys.executable, "tools/bench_eval.py", "run", "--items", ITEMS, "--out",
                                    os.path.join(o, "bench"), "--scorer", "hfgguf", "--model",
                                    f"{tag}_{v}={os.path.join(vd, 'spec.json')}", "--blimp-per", "100"],
                                   cwd=REPO, stdout=log, stderr=subprocess.STDOUT)
            sm = os.path.join(o, "bench", f"{tag}_{v}", "summary.json")
            if p.returncode != 0 or not os.path.exists(sm):
                raise SystemExit(f"{tag} {v}: bench_eval failed (rc {p.returncode}; {o}/bench.log)")
            rec["bench"] = jload(sm)
            jsave(summ_path, summ)
        print(json.dumps({"tag": tag, "variant": v, "panels": rec["panels"]}), flush=True)
    jsave(summ_path, summ)
    return 0


def cmd_carry5(out, tag, v):
    import tiny_chat_run as tc
    _, s, ggufs = stage(tag)
    vd, spec, w = variant_dir(tag, v, s, ggufs[v])
    os.environ.update(DEV_ENV)
    res = {"tag": tag, "variant": v, "gguf_sha256": sha256(ggufs[v]), "weights_sha256": sha256(w)}
    # tiny_chat_run.choose_engine without its F32 re-export (which would write through the link to the
    # quantised file): ember at tiny_chat_run's pinned commit on the quantised GGUF, spot-checked against
    # `mtstudio chat` on the dequantised weights; N/N or mtstudio throughout.
    path = os.path.join(out, "gen_engine.json")
    if os.path.exists(path):
        eng = jload(path)
    else:
        eng = {"engine": "mtstudio", "ember_commit_pinned": tc.EMBER_COMMIT, "ember_env": dict(tc.EMBER_ENV),
               "flag": None}
        eb_build = tc.ensure_ember(os.path.join(out, "ember_build.log"))
        eng["ember_build"] = eb_build
        if "error" in eb_build:
            eng["flag"] = f"ember unavailable ({eb_build['error'][:300]}); generated with mtstudio"
        else:
            eb = {"bin": eb_build["bin"], "gpu_layers": tc.EMBER_GPU_LAYERS}
            env0 = {**os.environ, **tc.EMBER_ENV}
            spot = tc.spot_check(os.path.join(vd, "spec.json"), CARRY5_ITEMS, os.path.join(out, "spot"), eb, env0,
                                 "default")
            eng["spot"] = spot
            if spot["pass"]:
                eng["engine"], eng["ember"] = "ember", eb
            else:
                eng["flag"] = f"ember spot-check {spot['identical']}/{spot['n']}; generated with mtstudio throughout"
        jsave(path, eng)
    res["gen_engine"] = eng
    env = dict(os.environ)
    ember = None
    if eng["engine"] == "ember":
        ember = eng["ember"]
        env.update(eng["ember_env"])
    c5 = os.path.join(out, "carry5")
    t0 = time.time()
    p = subprocess.run(tc.carry5_argv(os.path.join(vd, "spec.json"), CARRY5_ITEMS, c5, "ember" if ember else "mtstudio",
                                      tc.port_for(out), ember=ember), cwd=REPO, capture_output=True, text=True, env=env)
    res["carry5_seconds"] = round(time.time() - t0, 1)
    open(os.path.join(out, "carry5.log"), "w").write(p.stdout[-20000:] + p.stderr[-20000:])
    if p.returncode != 0 or not os.path.exists(os.path.join(c5, "summary.json")):
        raise SystemExit(f"carry5_eval failed (rc {p.returncode}): {p.stderr[-800:]}")
    c = tc.carry5_read(c5)
    res["carry5"] = c
    res["primary"] = tc.primary(c)
    res["primary_all_items"] = tc.primary_all_items(c)
    jsave(os.path.join(out, "summary.json"), res)
    print(json.dumps({k: res[k] for k in ("tag", "variant", "primary")}))
    return 0


def cmd_bench_mt(out, spec_path):
    items()
    s = jload(spec_path)
    tag = s["name"]
    with open(os.path.join(out, "bench.log"), "a") as log:
        p = subprocess.run([sys.executable, "tools/bench_eval.py", "run", "--items", ITEMS, "--out",
                            os.path.join(out, "bench"), "--scorer", "mtstudio", "--mtstudio", MT, "--model",
                            f"{tag}={spec_path}", "--blimp-per", "100"], cwd=REPO, stdout=log,
                           stderr=subprocess.STDOUT, env={**os.environ, **DEV_ENV})
    sm = os.path.join(out, "bench", tag, "summary.json")
    if p.returncode != 0 or not os.path.exists(sm):
        raise SystemExit(f"bench_eval mtstudio failed (rc {p.returncode})")
    shutil.copyfile(sm, os.path.join(out, "bench_summary.json"))
    return 0


def main():
    cmd, out = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)
    os.chdir(REPO)
    if cmd == "gate":
        return cmd_gate(out)
    if cmd == "ptq":
        return cmd_ptq(out, sys.argv[3])
    if cmd == "carry5":
        return cmd_carry5(out, sys.argv[3], sys.argv[4])
    if cmd == "bench_mt":
        return cmd_bench_mt(out, sys.argv[3])
    raise SystemExit(f"unknown command {cmd}")


if __name__ == "__main__":
    sys.exit(main())
