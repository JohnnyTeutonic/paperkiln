#!/usr/bin/env python3
"""Regenerate the Unicode tables of include/microtorch/llama3_unicode_tables.hpp
from llama.cpp's src/unicode-data.cpp (MIT, the ggml authors).

    python tools/gen_llama3_tables.py LLAMA_CPP/src/unicode-data.cpp --tag b6000

Only what the Llama 3 pre-tokeniser reads is kept: the category flags by
range (llama.cpp's unicode_ranges_flags, start code point and flag bits) and
the whitespace set. Ranges are kept as llama.cpp lists them, so a binary
search gives the same flags as llama.cpp's per-code-point array.
"""
from __future__ import annotations

import argparse
import hashlib
import os
import re

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "include", "microtorch",
                   "llama3_unicode_tables.hpp")


def block(src, name):
    a = src.index(name + " = {")
    return src[a:src.index("};", a)]


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("unicode_data")
    ap.add_argument("--tag", required=True, help="the llama.cpp release the file came from")
    a = ap.parse_args()
    raw = open(a.unicode_data, "rb").read()
    src = raw.decode("utf-8")
    ranges = [(int(s, 16), int(f, 16)) for s, f in
              re.findall(r"\{0x([0-9A-Fa-f]+),\s*0x([0-9A-Fa-f]+)\}", block(src, "unicode_ranges_flags"))]
    ws = [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]+)", block(src, "unicode_set_whitespace"))]
    assert ranges[0][0] == 0 and ranges[-1][0] == 0x110000, "unexpected range table bounds"
    assert all(x < y for (x, _), (y, _) in zip(ranges, ranges[1:])), "ranges not ascending"
    # Every code point below 0x110000 then has a non-zero flag word (llama.cpp's
    # as_uint() test in the punctuation rule), which the encoder relies on.
    assert all(f & 0xFF for _, f in ranges[:-1]), "a range with no category"
    ws = sorted(set(ws))
    L = ["#pragma once",
         f"// Generated by tools/gen_llama3_tables.py from llama.cpp {a.tag} src/unicode-data.cpp",
         f"// (sha256 {hashlib.sha256(raw).hexdigest()}; MIT License, Copyright (c) 2023-2024 The ggml",
         "// authors). Do not edit: regenerate. Category flags by range: code points from",
         "// kRangeStart[i] up to kRangeStart[i + 1] - 1 have kRangeFlags[i] (0x0001 undefined,",
         "// 0x0002 \\p{N}, 0x0004 \\p{L}, 0x0008 \\p{Z}, 0x0010 \\p{M}, 0x0020 \\p{P}, 0x0040 \\p{S},",
         "// 0x0080 \\p{C}); the last entry is 0x110000.",
         "#include <cstdint>", "", "namespace microtorch {", "namespace llama3 {", "namespace tables {", "",
         f"inline constexpr uint32_t kRangeCount = {len(ranges)};",
         "inline constexpr uint32_t kRangeStart[kRangeCount] = {"]
    for i in range(0, len(ranges), 10):
        L.append("    " + ", ".join(f"0x{s:06X}" for s, _ in ranges[i:i + 10]) + ",")
    L += ["};", "inline constexpr uint16_t kRangeFlags[kRangeCount] = {"]
    for i in range(0, len(ranges), 12):
        L.append("    " + ", ".join(f"0x{f:04X}" for _, f in ranges[i:i + 12]) + ",")
    L += ["};", f"inline constexpr uint32_t kWhitespaceCount = {len(ws)};",
          "inline constexpr uint32_t kWhitespace[kWhitespaceCount] = {"]
    for i in range(0, len(ws), 10):
        L.append("    " + ", ".join(f"0x{c:06X}" for c in ws[i:i + 10]) + ",")
    L += ["};", "", "}  // namespace tables", "}  // namespace llama3", "}  // namespace microtorch", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L))
    print(f"{OUT}: {len(ranges)} ranges, {len(ws)} whitespace code points")


if __name__ == "__main__":
    main()
