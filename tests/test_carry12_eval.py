            g = c == it["gold_index"]
            scores[f"{it['id']}|gold|{c}"] = {"over_ctx": False, "sum": 0.0 if g else -1.0, "logprobs": [0.0], "argmax": []}
            scores[f"{it['id']}|near|{c}"] = {"over_ctx": False, "sum": 0.0 if g else -1.0, "logprobs": [0.0], "argmax": []}
