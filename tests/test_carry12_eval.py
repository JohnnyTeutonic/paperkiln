def test_renderings():
    it = next(x for x in items() if x["family"] == "recall" and x["interference"] == 2)
    hist, user = c12e.gold_history(it)
    assert len(hist) == it["target_turn"] - 1 and user == it["turns"][it["target_turn"] - 1]["user"]
    nh, nu = c12e.near_history(it)
    assert nu == user and len(nh) == it["near_target"] - 1 == 3  # plant and two distractors
    kinds = [k for k in it["turn_kinds"][:it["target_turn"] - 1] if k not in ("opener", "small_talk", "digression")]
    assert [u for u, _ in nh] == [t["user"] for t, k in zip(it["turns"], it["turn_kinds"]) if k in kinds][:3]


def test_instruction_verdicts():
    it = next(x for x in items() if x["family"] == "instruction" and x["check"]["kind"] == "closer")
    gold = it["candidates"][it["gold_index"]]
    assert c12e.verdicts(it, gold)["complies"]
    assert not any(c12e.verdicts(it, c)["complies"] for c in it["candidates"] if c != gold)
    op = next(x for x in items() if x["family"] == "instruction" and x["check"]["kind"] == "opener")
    w = op["check"]["form"]
    assert c12e.verdicts(op, f"{w.lower()}! yes")["complies"] and not c12e.verdicts(op, "No.")["complies"]


class FakeTok:
    eot = 1

    def encode(self, s):
        return [len(s) % 7 + 2, 3]


def fake_gen(it, reply="ok"):
    def rec(k=0):
        return {"reply": reply, "stop": "eos", "history_used": k, "dropped": False, "ids": [5], "stop_id": None}
    return {"id": it["id"], "self_scope": "whole", "self": [rec(k) for k in range(it["n_turns"])],
            "gold": rec(), "near": rec(), "twin": rec(), "noctx": rec(),
            "near_self": [rec(k) for k in range(it["near_target"])]}


def test_requests_gate_rows_and_curves_to_turn_14():
    its = [x for x in items() if x["n_turns"] == 14][:5]
    gens = {it["id"]: fake_gen(it) for it in its}
    reqs = c12e.requests(its, FakeTok(), gens)
    keys = {k for k, _, _ in reqs}
    for it in its:
        for mode in c12e.MODES:
            assert all(f"{it['id']}|{mode}|{c}" in keys for c in range(4))
        assert sum(1 for k in keys if k.startswith(it["id"] + "|gate_self|")) == 14
        assert sum(1 for k in keys if k.startswith(it["id"] + "|gate_near_self|")) == it["near_target"]
    # The scorer agrees with every reply (argmax = ids + eot): the gate is all identical; the gold is chosen.
    scores = {}
    for k, p, c in reqs:
        iid, mode, rest = k.split("|")
        it = next(x for x in its if x["id"] == iid)
        good = mode.startswith("gate") or int(rest) == it["gold_index"]
        scores[k] = {"over_ctx": False, "sum": -1.0 if good else -2.0, "logprobs": [-0.5] * len(c), "argmax": c}
    recs = c12e.item_records(its, gens, scores, FakeTok())
    s = c12e.aggregate(recs)
    assert s["gate"]["replies"] == s["gate"]["argmax_identical"] == sum(14 + it["near_target"] for it in its)
    assert sorted(s["decay"], key=int) == [str(k) for k in range(1, 15)] and s["decay"]["14"]["n"] == 5
    assert all(s["fc"]["acc"][m]["all"]["mean"] == 1.0 for m in c12e.MODES)
    assert s["derived"]["distance_cost_gold"] == 0.0


def test_derived_and_overflow():
    its = [x for x in items() if x["family"] == "recall"][:8]
    scores = {}
    for it in its:
        for c in range(4):
            gold = c == it["gold_index"]
            scores[f"{it['id']}|gold|{c}"] = {"over_ctx": False, "sum": 0.0, "logprobs": [0.0], "argmax": []}
            scores[f"{it['id']}|near|{c}"] = {"over_ctx": False, "sum": 0.0 if gold else -1.0, "logprobs": [0.0],
                                              "argmax": []}
            scores[f"{it['id']}|twin|{c}"] = {"over_ctx": it is its[0], "sum": 0.0 if gold else -1.0,
                                              "logprobs": [0.0], "argmax": []}
            scores[f"{it['id']}|noctx|{c}"] = {"over_ctx": False, "sum": 0.0, "logprobs": [0.0], "argmax": []}
    s = c12e.aggregate(c12e.item_records(its, {}, scores, None))
    assert s["fc"]["acc"]["gold"]["all"]["mean"] == 0.25 and s["fc"]["acc"]["near"]["all"]["mean"] == 1.0
    assert s["derived"]["distance_cost_gold"] == -0.75  # HL0's quantity: gold minus near
    assert s["fc"]["over_ctx"]["twin"] == 1 and s["fc"]["acc"]["twin"]["all"]["mean"] == 7 / 8
    assert s["fc"]["acc_fit"]["twin"]["all"]["mean"] == 1.0 and s["fc"]["acc_fit"]["twin"]["all"]["n"] == 7
    assert s["derived"]["validity_gate"]["twin_minus_noctx_at_least_0.10"] is True
    assert c12e.ols_slope([(1, 1.0), (2, 0.5), (3, 0.0)])["slope"] == -0.5


def test_spot_check_compare_and_spread():
    its = items()
    sp = c12e.spot_items(its, 40)
    assert len(sp) == 40 and len({it["family"] for it in sp}) == 6
    a = {it["id"]: fake_gen(it) for it in sp[:3]}
    b = json.loads(json.dumps(a))
    assert c12e.compare(a, b, list(a))["items_identical"] == 3
    b[sp[1]["id"]]["self"][7]["reply"] = "different"
    cmp = c12e.compare(a, b, list(a))
    assert cmp["items_identical"] == 2 and cmp["differing"][0]["diff"][0]["reply"] == "self8"


