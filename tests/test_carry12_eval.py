def run_eval(out, sp, *extra):
    argv = TOOL + ["run", "--model", f"m={sp}", "--out", str(out), "--mtstudio", BIN, "--every", "110",
                   "--max-new", "8", *extra]
    r = subprocess.run(argv, capture_output=True, text=True, cwd=ROOT, timeout=3600)
    assert r.returncode == 0, r.stdout[-3000:] + r.stderr[-3000:]
    return json.loads((out / "summary.json").read_text())


@e2e
def test_end_to_end_mtstudio_whole_conversation(toy, tmp_path):
    _, sp = toy
    s = run_eval(tmp_path / "e", sp, "--gen", "mtstudio", "--self-scope", "whole", "--port", "8191")
    m = s["models"]["m"]
    assert m["items"] == 14 and m["context"] == 1024 and m["gen_engine"]["engine"] == "mtstudio"
    assert {r["family"] for r in ce.read_jsonl(tmp_path / "e" / "m" / "items.jsonl")} == set(c12.FAMILY_SIZES)
    for mode in c12e.MODES:
        assert m["fc"]["acc"][mode]["all"]["n"] == 14, mode
    assert m["fc"]["over_ctx"]["gold"] == 0  # the toy's T 1,024 holds every gold history
    # `mtstudio chat` returns no token ids, so its replies are not gated (as Carry-5; ember's are, below).
    assert m["gate"]["replies"] == 0 and m["gen"]["server_errors"] <= 4, (m["gate"], m["gen"]["server_errors"])
    assert "14" in m["decay"] and m["gen"]["complies"]["gold"]["all"]["n"] == 1
    # report re-aggregates the same numbers without generating
    r = subprocess.run(TOOL + ["report", "--out", str(tmp_path / "e"), "--mtstudio", BIN], capture_output=True,
                       text=True, cwd=ROOT)
    assert r.returncode == 0, r.stderr[-2000:]
    assert json.loads((tmp_path / "e" / "summary.json").read_text())["models"]["m"]["fc"] == m["fc"]


