    text = " ".join(x["user"] + " " + x["gold"] for it in its for x in it["turns"])
    bpe.write_gguf(str(t / "v.gguf"), bpe.train(text, 400))
    ex = [{"prompt": ce.template(*c12e.gold_history(it)), "completion": it["turns"][it["target_turn"] - 1]["gold"]}
          for it in its]
    (t / "ex.jsonl").write_text("".join(json.dumps(e) + "\n" for e in ex), encoding="utf-8")
    spec = {"name": "c12toy", "arch": {"preset": "llama-tiny", "rope_heads": "all",
                                       "custom": {"d": 32, "layers": 2, "heads": 2, "d_ff": 64}},
            "data": {"vocab": str(t / "v.gguf"), "vocab_cap": 4096, "T": 1024, "sft_examples": str(t / "ex.jsonl")},
            "train": {"steps": 120, "lr": 0.003, "batch": 2, "eval_every": 120, "checkpoint_every": 1000,
                      "gradmap_every": 0, "seed": 1, "objective": "sft"},
            "export": {"formats": ["safetensors", "gguf"]}, "out_dir": str(t / "run")}
    sp = t / "spec.json"
    sp.write_text(json.dumps(spec), encoding="utf-8")
